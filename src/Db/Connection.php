<?php

declare(strict_types=1);

namespace app\Db;

/**
 * Тонкий подкласс соединения БД — нужен, чтобы разорвать круг в контейнере.
 *
 * В `config/container.php` объявлено: любая зависимость с тайп-хинтом
 * {@see \yii\db\Connection} получает компонент приложения `db`. Это то, что
 * позволяет мапперам и репозиторию просто просить соединение конструктором.
 *
 * Но если бы сам компонент `db` был объявлен классом {@see \yii\db\Connection},
 * его создание пошло бы через это же определение: компонент → определение
 * контейнера → компонент. Круг.
 *
 * Что при этом происходит на самом деле — проверено, а не выведено из общих
 * соображений. Бесконечной рекурсии не будет: PHP не входит в `__get` повторно
 * для того же свойства того же объекта, поэтому вложенное обращение к
 * `Yii::$app->db` проваливается в обычный поиск свойства и даёт
 * `Undefined property: Application::$db`. Компонент просто не создаётся.
 *
 * Собственный тип разрывает круг: `Yii::createObject()` для этого класса не
 * находит в контейнере определения и строит объект напрямую — определение
 * при создании компонента не вызывается ни разу. А потребители, просящие
 * базовый тип, получают через него этот же самый экземпляр.
 *
 * Альтернатива без подкласса — отказаться от определения по типу и просить
 * соединение через `Instance::of('db')`. Тогда тайп-хинты в мапперах перестают
 * быть точкой связывания, что здесь и было нужно.
 */
final class Connection extends \yii\db\Connection
{
}
